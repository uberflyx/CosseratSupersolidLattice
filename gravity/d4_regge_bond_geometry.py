def metric_basis():
    basis = []
    for a in range(4):
        for b in range(a, 4):
            E = np.zeros((4, 4)); E[a, b] = E[b, a] = 1.0
            basis.append(E)
    return basis


def eh_second_order(h, k):
    """Space average of the second-order part of sqrt(g) R for g = delta + h cos(k.x)."""
    kh, tr = k @ h, np.trace(h)
    return 0.5 * (-0.25 * (k @ k) * np.sum(h * h) + 0.5 * kh @ kh
                  - 0.5 * (k @ h @ k) * tr + 0.25 * (k @ k) * tr ** 2)


def eh_form(k, basis):
    """Continuum energy per cell, (V_cell/2) [sqrt(g) R]^(2), as a 10x10 form."""
    out = np.zeros((10, 10))
    for i, bi in enumerate(basis):
        for j, bj in enumerate(basis):
            out[i, j] = 0.5 * V_CELL * 0.5 * (eh_second_order(bi + bj, k)
                                              - eh_second_order(bi, k) - eh_second_order(bj, k))
    return out


def effective_metric_form(Hk, M, k, tol=1e-9):
    """Energy per cell as a 10x10 form on metric components, after projecting
    out exact zero modes and integrating out the non-metric complement."""
    Hm = Hk(k)
    w, U = np.linalg.eigh(Hm)
    Z = U[:, np.abs(w) < tol * np.abs(w).max()]
    Mp = M - Z @ (Z.conj().T @ M)
    B = np.hstack([Z, Mp])
    Q, _ = np.linalg.qr(B, mode='complete')
    N = Q[:, np.linalg.matrix_rank(B, tol=1e-10):]
    HMM = Mp.conj().T @ Hm @ Mp
    if N.shape[1]:
        HMN = Mp.conj().T @ Hm @ N
        HMM = HMM - HMN @ np.linalg.solve(N.conj().T @ Hm @ N, HMN.conj().T)
    return 0.25 * np.real(HMM), Z.shape[1]


