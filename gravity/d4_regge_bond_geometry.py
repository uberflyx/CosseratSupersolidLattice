def dihedral_angles(L2):
    """Interior dihedral angles of four-simplices at their ten triangles,
    from the ten squared edge lengths L2[..., PAIRS order]."""
    idx = {p: k for k, p in enumerate(PAIRS)}
    l2 = lambda a, b: L2[..., idx[(min(a, b), max(a, b))]]
    G = np.empty(L2.shape[:-1] + (4, 4), L2.dtype)
    for i in range(1, 5):
        for j in range(1, 5):
            lij = 0 * L2[..., 0] if i == j else l2(i, j)
            G[..., i - 1, j - 1] = 0.5 * (l2(0, i) + l2(0, j) - lij)
    C = np.vstack([-np.ones(4), np.eye(4)])          # barycentric gradients
    M = np.einsum('ai,...ij,bj->...ab', C, np.linalg.inv(G), C)
    out = np.empty(L2.shape[:-1] + (10,), L2.dtype)
    for ti, tri in enumerate(TRIPLES):
        d, e = [v for v in range(5) if v not in tri]
        out[..., ti] = np.arccos(-M[..., d, e] / np.sqrt(M[..., d, d] * M[..., e, e]))
    return out


def regge_hessian(cx):
    """Sparse Hessian of S = sum_f A_f delta_f at the flat configuration."""
    S = len(cx['simplices'])
    L = np.array([[np.linalg.norm(p[b] - p[a]) for a, b in PAIRS] for _, p in cx['simplices']])
    theta = dihedral_angles(L ** 2).real
    step = 1e-30
    dtheta = np.empty((S, 10, 10))
    for e in range(10):
        Lc = L.astype(complex)
        Lc[:, e] += 1j * step
        dtheta[:, :, e] = dihedral_angles(Lc ** 2).imag / step
    T = len(cx['tris'])
    angle_sum = np.zeros(T)
    np.add.at(angle_sum, cx['s_tris'].ravel(), theta.ravel())
    deficit = 2 * np.pi - angle_sum
    elen = np.array([np.linalg.norm(d) for _, _, d in cx['edges']])
    eid = cx['eid']
    tri_edges = np.array([[eid[frozenset((a, b))], eid[frozenset((b, c))], eid[frozenset((a, c))]]
                          for a, b, c in cx['tris']])
    la, lb, lc = (elen[tri_edges[:, k]] for k in range(3))
    area = 0.25 * np.sqrt(2 * la**2 * lb**2 + 2 * lb**2 * lc**2 + 2 * lc**2 * la**2
                          - la**4 - lb**4 - lc**4)
    darea = np.stack([la * (lb**2 + lc**2 - la**2), lb * (la**2 + lc**2 - lb**2),
                      lc * (la**2 + lb**2 - lc**2)], 1) / (8 * area[:, None])
    rows, cols, vals = [], [], []
    for ti in range(10):
        f = cx['s_tris'][:, ti]
        for k in range(3):
            for el in range(10):
                rows.append(tri_edges[f, k])
                cols.append(cx['s_edges'][:, el])
                vals.append(-darea[f, k] * dtheta[:, ti, el])
    E = len(cx['edges'])
    H = sparse.coo_matrix((np.concatenate(vals), (np.concatenate(rows), np.concatenate(cols))),
                          shape=(E, E)).tocsr()
    return H, deficit


def translation_classes(cx):
    """Group edges into translation classes (endpoint types and displacement)."""
    vt = cx['vtype']
    keys, cls = {}, []
    for i, j, d in cx['edges']:
        k1 = (vt[i], vt[j], tuple(np.round(2 * d).astype(int)))
        k2 = (vt[j], vt[i], tuple(np.round(-2 * d).astype(int)))
        key = min(k1, k2)
        keys.setdefault(key, len(keys))
        cls.append(keys[key])
    disp = np.zeros((len(keys), 4))
    types = [None] * len(keys)
    for (ti, tj, d2), c in keys.items():
        disp[c] = np.array(d2, float) / 2
        types[c] = (ti, tj)
    return np.array(cls), disp, types


def bloch_operator(cx, H):
    """Return k -> H(k) on the translation classes, and the class geometry."""
    cls, disp, types = translation_classes(cx)
    n, vpos = cx['n'], cx['vpos']
    mid = np.array([vpos[i] + d / 2 for i, _, d in cx['edges']])
    ref = {}
    for e, c in enumerate(cls):
        ref.setdefault(c, e)
    nc = len(disp)

    def Hk(k):
        out = np.zeros((nc, nc), complex)
        for a in range(nc):
            row = H.getrow(ref[a])
            dx = mid[row.indices] - mid[ref[a]]
            dx = (dx + n / 2) % n - n / 2
            np.add.at(out[a], cls[row.indices], row.data * np.exp(1j * dx @ k))
        return out
    return Hk, cls, disp, types, mid


