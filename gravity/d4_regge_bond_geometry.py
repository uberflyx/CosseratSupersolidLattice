def longitudinal_speeds(lam, mu, A, B):
    """Phase speeds w/(ck) of the (u_x, u_4) block for a wave along x, with
    four-dimensional Lame constants lam, mu and extra u_4 stiffnesses A
    (spatial gradients) and B (compact-axis gradients).  Q = k4^2 at k = 1;
    a real speed s is a root Q = -s^2 of det M(Q) = 0."""
    a2 = mu * (lam + 2 * mu + B)
    a1 = (lam + 2 * mu) * (lam + 2 * mu + B) + mu * (mu + A) - (lam + mu) ** 2
    a0 = (lam + 2 * mu) * (mu + A)
    return np.roots([a2, a1, a0])


